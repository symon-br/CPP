// maths in cpp

#include <iostream>
#include <cmath>
using namespace std;

int main() {
    // square root
    cout << "Square root of 64 is: " << sqrt(64) << endl;

    // power
    cout << "2 raised to the power 3 is: " << pow(2, 3) << endl;

    // absolute value
    cout << "Absolute value of -5 is: " << abs(-5) << endl;

    // round
    cout << "Round of 4.6 is: " << round(4.6) << endl;

    // ceil
    cout << "Ceil of 4.2 is: " << ceil(4.2) << endl;

    // floor
    cout << "Floor of 4.8 is: " << floor(4.8) << endl;

    
    return 0;
}